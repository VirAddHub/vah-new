#!/usr/bin/env python3
"""Which checklist routes do the automated tests exercise?

Reads audit/CHECKLIST.md (backend route tables), scans request paths used by
apps/backend/tests/journey/*.mjs (end-to-end, real database) and apps/backend/src/tests/**/*.ts
(Vitest), ticks routes the journey suites exercise, and writes audit/ROUTE-COVERAGE.md.
Run from the repository root: python3 scripts/tools/route_coverage.py
"""
import glob, re, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
check = root / 'audit' / 'CHECKLIST.md'

def literals(files):
    out = set()
    for f in files:
        s = open(f, encoding='utf-8', errors='ignore').read()
        for m in re.finditer(r"""[`'"](/api/[^`'"\s?]*)""", s):
            out.add(re.sub(r'\$\{[^}]+\}', 'X', m.group(1)).rstrip('/'))
    return out

journey = literals(glob.glob(str(root / 'apps/backend/tests/journey/*.mjs')))
unit = literals(glob.glob(str(root / 'apps/backend/src/tests/**/*.ts'), recursive=True))

def rx(route):
    pat = re.sub(r':[A-Za-z_]+', '[^/]+', re.escape(route).replace('\\:', ':'))
    return re.compile('^' + pat.rstrip('/') + '$')

rows, lines = [], open(check, encoding='utf-8').read().split('\n')
section = None
for i, line in enumerate(lines):
    if line.startswith('## '):
        section = line[3:].strip()
    m = re.match(r'^\| \[( |x)\] \| (GET|POST|PUT|PATCH|DELETE|ALL|USE) \| `([^`]+)` \|', line)
    if not m or section != 'Backend routes':
        continue
    done, method, route = m.groups()
    r = rx(route)
    j = any(r.match(p) for p in journey)
    u = any(r.match(p) for p in unit)
    rows.append((route, method, done == 'x', j, u))
    if j and done == ' ':
        lines[i] = line.replace('| [ ] |', '| [x] |', 1)

open(check, 'w', encoding='utf-8').write('\n'.join(lines))

tot = len(rows); j = sum(1 for r in rows if r[3]); u = sum(1 for r in rows if r[4] and not r[3])
none = [r for r in rows if not r[3] and not r[4]]
with open(root / 'audit' / 'ROUTE-COVERAGE.md', 'w', encoding='utf-8') as f:
    f.write('# Route coverage (generated by scripts/tools/route_coverage.py)\n\n')
    f.write(f'Backend routes in the checklist: **{tot}**. Exercised by the journey suites (real database, rate limits on): **{j}**. '
            f'Only by Vitest route tests (often auth/validation checks only): **{u}**. Not exercised by any test: **{len(none)}**.\n\n')
    f.write('Path matching is literal: a route reached through a computed URL may be listed as untested.\n\n')
    f.write('## Not exercised by any automated test\n\n| Method | Route |\n|---|---|\n')
    for r in none:
        f.write(f'| {r[1]} | `{r[0]}` |\n')
print(tot, j, u, len(none))
